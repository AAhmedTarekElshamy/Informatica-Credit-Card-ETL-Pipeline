CREATE SCHEMA TGT_DWH;
GO

CREATE TABLE TGT_DWH.CREDIT_CARDS_ARCHIVE (
    CC_SUR INT NOT NULL,
    CC_NUMBER VARCHAR(50) PRIMARY KEY,
    CC_NUMBER_MASKED VARCHAR(50),
    CC_BAL DECIMAL(18, 2),
    CC_LIMIT DECIMAL(18, 2),
    CC_OPEN_DATE DATE,
    ACCT_OPEN_DATE DATE,
    EMP_NAME VARCHAR(100),
    EMP_EMAIL VARCHAR(100),
    EMP_DEPT_NAME VARCHAR(100)
);

CREATE TABLE TGT_DWH.CREDIT_CARDS_CURRENT (
    CC_SUR INT NOT NULL,
    CC_NUMBER VARCHAR(50) PRIMARY KEY,
    CC_NUMBER_MASKED VARCHAR(50),
    CC_BAL DECIMAL(18, 2),

-- 1. Row counts (expected: ARCHIVE = 11, CURRENT = 9)
SELECT 'ARCHIVE' AS target, COUNT(*) AS cnt FROM TGT_DWH.CREDIT_CARDS_ARCHIVE
UNION ALL
SELECT 'CURRENT', COUNT(*) FROM TGT_DWH.CREDIT_CARDS_CURRENT;

-- 2. Masking check
SELECT CC_NUMBER, CC_NUMBER_MASKED
FROM TGT_DWH.CREDIT_CARDS_CURRENT;

-- 3. Cutoff split check (ARCHIVE should be before 2022-01-01)
SELECT MAX(CC_OPEN_DATE) AS latest_archive_date FROM TGT_DWH.CREDIT_CARDS_ARCHIVE;
SELECT MIN(CC_OPEN_DATE) AS earliest_current_date FROM TGT_DWH.CREDIT_CARDS_CURRENT;

-- 4. No duplicates (should return 0 rows)
SELECT CC_NUMBER, COUNT(*) AS cnt
FROM TGT_DWH.CREDIT_CARDS_CURRENT
GROUP BY CC_NUMBER HAVING COUNT(*) > 1;

-- 5. Surrogate keys are unique (should return 0 rows)
SELECT CC_SUR, COUNT(*) AS cnt
FROM TGT_DWH.CREDIT_CARDS_ARCHIVE
GROUP BY CC_SUR HAVING COUNT(*) > 1;

-- 6. Cards that should be rejected (expected: 1 row)
SELECT CC_NUMBER
FROM SRC.DEMO_CREDIT_CARD
WHERE LEN(REPLACE(CC_NUMBER, ' ', '')) < 16;

-- 7. Full output
SELECT * FROM TGT_DWH.CREDIT_CARDS_ARCHIVE ORDER BY CC_SUR;
SELECT * FROM TGT_DWH.CREDIT_CARDS_CURRENT ORDER BY CC_SUR;
